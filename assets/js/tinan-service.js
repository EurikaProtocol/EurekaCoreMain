function developerTemplate(language, prompt) {
  const safePrompt = prompt || "EurekaCore generated module";
  const stamp = `Generated by TINAN AI on ${nowLabel()}`;
  const templates = {
    solidity: {
      filename: `${slugify(safePrompt)}.sol`,
      content: `// ${stamp}\npragma solidity ^0.8.21;\n\ncontract EurekaCoreModule {\n    string public constant NAME = \"${safePrompt}\";\n\n    function version() external pure returns (string memory) {\n        return \"EurekaCore V3\";\n    }\n}\n`
    },
    html: {
      filename: `${slugify(safePrompt)}.html`,
      content: `<!-- ${stamp} -->\n<section class=\"eureka-module\">\n  <header>\n    <h1>${safePrompt}</h1>\n    <p>Built for the EurekaCore design system.</p>\n  </header>\n</section>\n`
    },
    css: {
      filename: `${slugify(safePrompt)}.css`,
      content: `/* ${stamp} */\n.eureka-module {\n  display: grid;\n  gap: 12px;\n  padding: 20px;\n  border-radius: 20px;\n  background: rgba(59, 243, 165, 0.08);\n  border: 1px solid rgba(59, 243, 165, 0.18);\n}\n`
    },
    javascript: {
      filename: `${slugify(safePrompt)}.js`,
      content: `// ${stamp}\nexport function initEurekaModule(root) {\n  if (!root) return;\n  root.dataset.ready = \"true\";\n}\n`
    },
    react: {
      filename: `${slugify(safePrompt)}.jsx`,
      content: `// ${stamp}\nexport function EurekaModule() {\n  return (\n    <section className=\"eureka-module\">\n      <h1>${safePrompt}</h1>\n      <p>React output prepared by TINAN AI.</p>\n    </section>\n  );\n}\n`
    },
    documentation: {
      filename: `${slugify(safePrompt)}.md`,
      content: `# ${safePrompt}\n\n_${stamp}_\n\n## Summary\n- Objective\n- Dependencies\n- Deployment notes\n\n## Acceptance\n- Ready for review\n`
    }
  };

  return templates[language] || templates.javascript;
}

export function buildProjectMemory(state) {
  const memory = [];
  memory.push(state.wallet.connected ? `Wallet connected: ${formatAddress(state.wallet.address)}` : "Wallet connection pending");
  memory.push(`Preferred network: ${state.preferences.preferredNetwork}`);
  memory.push(`Workspace files: ${state.workspace.files.length}`);
  const unlockedVaultKeys = Object.entries(state.vaultSummary).filter(([key, value]) => key !== "updatedAt" && Boolean(value));
  memory.push(unlockedVaultKeys.length ? `Vault categories saved: ${unlockedVaultKeys.length}` : "Vault categories saved: 0");
  return memory;
}

export function createAssistantReply({ message, agentId, state, token }) {
  const lower = message.toLowerCase();

  if (agentId === "developer" || /(solidity|html|css|javascript|react|documentation|workspace|generate)/.test(lower)) {
    const language = /(solidity)/.test(lower)
      ? "solidity"
      : /(react)/.test(lower)
        ? "react"
        : /(documentation|docs)/.test(lower)
          ? "documentation"
          : /(html)/.test(lower)
            ? "html"
            : /(css)/.test(lower)
              ? "css"
              : "javascript";
    const file = developerTemplate(language, message);
    return {
      text: `${AGENTS.find((item) => item.id === "developer").name}: I generated a ${language.toUpperCase()} workspace file and queued it for preview/export.`,
      file
    };
  }

  if (agentId === "wallet" || /(wallet|balance|send|receive|address|network)/.test(lower)) {
    return {
      text: state.wallet.connected
        ? `Wallet Agent: ${formatAddress(state.wallet.address)} is connected on ${state.wallet.network}. Native balance: ${formatNumber(state.wallet.nativeBalance, 4)}. ${token.symbol} balance: ${formatNumber(state.wallet.tokenBalance, 4)}.`
        : "Wallet Agent: No wallet is connected yet. Use MetaMask to load live balances or keep WalletConnect v2 and Coinbase Wallet prepared from config.js."
    };
  }

  if (agentId === "token" || /(token|eurika|eureka|holders|supply|contract|explorer)/.test(lower)) {
    return {
      text: `Token Agent: ${token.name} (${token.symbol}) resolves to ${token.contractAddress}. Total supply display: ${token.totalSupply}. Holder counter: ${token.holderCount}.`
    };
  }

  if (agentId === "knowledge" || /(vault|knowledge|note|whitepaper|roadmap|idea|memory)/.test(lower)) {
    const categories = Object.entries(state.vaultSummary)
      .filter(([key, value]) => key !== "updatedAt" && value)
      .map(([key]) => key);
    return {
      text: categories.length
        ? `Knowledge Agent: Your encrypted vault currently has saved content in ${categories.join(", ")}. I can help organize those into actionable milestones.`
        : "Knowledge Agent: Your encrypted vault is ready. Unlock it with a passphrase and store notes, whitepaper drafts, roadmap items, and ideas locally."
    };
  }

  return {
    text: `TINAN AI: ${state.wallet.connected ? "wallet online" : "wallet offline"}, ${state.workspace.files.length} workspace files tracked, and ${state.chatHistory.length} chat entries preserved. Ask about wallets, token telemetry, knowledge structure, or code generation.`
  };
}

export function createChatEntry(role, content, agentId) {
  return {
    id: `${role}-${Date.now()}-${Math.random().toString(16).slice(2)}`,
    role,
    content,
    agentId,
    createdAt: nowLabel()
  };
}
